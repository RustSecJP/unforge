//! A reader for the `[[package]]` entries of a `Cargo.lock`.
//!
//! Only `name`, `version` and `source` are needed, and cargo writes them as
//! plain `key = "value"` lines (lock file versions 1 to 4), so this does not
//! pull in a TOML parser.

use crate::model::Package;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockEntry {
    pub name: String,
    pub version: String,
    /// `registry+...`, `sparse+...`, `git+...`, or `None` for workspace
    /// members (the package being built).
    pub source: Option<String>,
}

impl LockEntry {
    pub fn is_registry(&self) -> bool {
        self.source
            .as_deref()
            .is_some_and(|s| s.starts_with("registry+") || s.starts_with("sparse+"))
    }

    pub fn package(&self) -> Package {
        Package {
            name: self.name.clone(),
            version: self.version.clone(),
        }
    }
}

pub fn parse(lock: &str) -> Vec<LockEntry> {
    let mut out = Vec::new();
    let mut cur: Option<(Option<String>, Option<String>, Option<String>)> = None;
    let mut flush = |cur: &mut Option<(Option<String>, Option<String>, Option<String>)>| {
        if let Some((Some(name), Some(version), source)) = cur.take() {
            out.push(LockEntry {
                name,
                version,
                source,
            });
        }
    };
    for line in lock.lines() {
        let line = line.trim();
        if line.starts_with('[') {
            flush(&mut cur);
            if line == "[[package]]" {
                cur = Some((None, None, None));
            }
            continue;
        }
        let Some(entry) = cur.as_mut() else { continue };
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        let value = value.trim();
        let Some(value) = value
            .strip_prefix('"')
            .and_then(|v| v.strip_suffix('"'))
            .map(str::to_owned)
        else {
            continue;
        };
        match key.trim() {
            "name" => entry.0 = Some(value),
            "version" => entry.1 = Some(value),
            "source" => entry.2 = Some(value),
            _ => {}
        }
    }
    flush(&mut cur);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_packages() {
        let lock = r#"# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "aho-corasick"
version = "1.1.3"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "8e60d3430d3a69478ad0993f19238d2df97c507009a52b3c10addcd7f6bcb916"
dependencies = [
 "memchr",
]

[[package]]
name = "ripgrep"
version = "14.1.1"
dependencies = [
 "grep",
]

[metadata]
"#;
        let v = parse(lock);
        assert_eq!(v.len(), 2);
        assert_eq!(v[0].name, "aho-corasick");
        assert!(v[0].is_registry());
        assert_eq!(v[1].name, "ripgrep");
        assert_eq!(v[1].version, "14.1.1");
        assert!(!v[1].is_registry());
    }
}
