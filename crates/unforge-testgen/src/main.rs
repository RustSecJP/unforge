//! Generator and helpers for the anomalous-ELF corpus in `testdata/anomalous`.
//!
//! ```text
//! unforge-testgen generate [--root <repo>]
//!     Write testdata/anomalous/files/<arch>/<name>.elf and files/MANIFEST.tsv
//!     from the committed seeds. Output depends only on the seed bytes.
//! unforge-testgen binfmt-match <snapshot> <file>
//!     Print the binfmt_misc entries of <snapshot> whose magic/mask match
//!     <file> ("a|b"), or "none". Used by run_oracle.sh to decide whether the
//!     kernel's own ELF loader or an emulator handled a file.
//! ```

#![forbid(unsafe_code)]

mod binfmt;
mod elf;
mod tiny;
mod variants;

use std::path::{Path, PathBuf};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Arch {
    Aarch64,
    X86_64,
}

impl Arch {
    pub fn dir(self) -> &'static str {
        match self {
            Arch::Aarch64 => "aarch64",
            Arch::X86_64 => "x86_64",
        }
    }
}

fn default_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn read(p: &Path) -> Vec<u8> {
    std::fs::read(p).unwrap_or_else(|e| panic!("read {}: {e}", p.display()))
}

#[cfg(unix)]
fn make_executable(p: &Path) {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(p, std::fs::Permissions::from_mode(0o755))
        .unwrap_or_else(|e| panic!("chmod {}: {e}", p.display()));
}
#[cfg(not(unix))]
fn make_executable(_: &Path) {}

fn generate(root: &Path) {
    let anomalous = root.join("testdata/anomalous");
    let seeds = anomalous.join("seeds/bin");
    let out = anomalous.join("files");
    let mut manifest = String::from(
        "# Generated by `cargo run -p unforge-testgen -- generate`. Do not edit.\n\
         # path\tarch\tname\ttechnique\tseed\tsize\twhat\n",
    );
    let mut total = 0usize;
    let mut count = 0usize;
    for arch in [Arch::Aarch64, Arch::X86_64] {
        let dir = out.join(arch.dir());
        std::fs::create_dir_all(&dir).expect("create output dir");
        // Remove stale outputs so a renamed variant does not linger.
        for e in std::fs::read_dir(&dir).expect("read output dir").flatten() {
            if e.path().extension().is_some_and(|x| x == "elf") {
                std::fs::remove_file(e.path()).expect("remove stale file");
            }
        }
        let static_seed = read(&seeds.join(arch.dir()).join("marker-static"));
        let pie_seed = seeds.join(arch.dir()).join("marker-static-pie");
        let pie_seed = pie_seed.exists().then(|| read(&pie_seed));
        for v in variants::all() {
            if !v.arches.contains(&arch) {
                continue;
            }
            let seed = match v.seed {
                variants::Seed::Static => elf::Elf::new(static_seed.clone()),
                variants::Seed::StaticSyms => {
                    let mut e = elf::Elf::new(static_seed.clone());
                    variants::add_symtab(&mut e);
                    e
                }
                variants::Seed::StaticPie => {
                    elf::Elf::new(pie_seed.clone().expect("static-pie seed for this arch"))
                }
                // Hand-made variants ignore the seed; any valid image will do.
                variants::Seed::None => elf::Elf::new(static_seed.clone()),
            };
            let bytes = (v.build)(arch, seed);
            let rel = format!("files/{}/{}.elf", arch.dir(), v.name);
            let path = anomalous.join(&rel);
            std::fs::write(&path, &bytes).unwrap_or_else(|e| panic!("write {rel}: {e}"));
            make_executable(&path);
            manifest.push_str(&format!(
                "{rel}\t{}\t{}\t{}\t{:?}\t{}\t{}\n",
                arch.dir(),
                v.name,
                v.technique,
                v.seed,
                bytes.len(),
                v.what
            ));
            total += bytes.len();
            count += 1;
        }
    }
    std::fs::write(out.join("MANIFEST.tsv"), manifest).expect("write MANIFEST.tsv");
    eprintln!(
        "wrote {count} files, {total} bytes, under {}",
        out.display()
    );
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("generate") => {
            let root = match args.get(1).map(String::as_str) {
                Some("--root") => PathBuf::from(args.get(2).expect("--root <dir>")),
                _ => default_root(),
            };
            generate(&root);
        }
        Some("binfmt-match") => {
            let (Some(snap), Some(file)) = (args.get(1), args.get(2)) else {
                eprintln!("usage: unforge-testgen binfmt-match <snapshot> <file>");
                std::process::exit(2);
            };
            let entries = binfmt::parse(&String::from_utf8_lossy(&read(Path::new(snap))));
            let hits = binfmt::matching(&entries, &read(Path::new(file)));
            println!(
                "{}",
                if hits.is_empty() {
                    "none".to_string()
                } else {
                    hits.join("|")
                }
            );
        }
        _ => {
            eprintln!(
                "usage: unforge-testgen generate [--root <repo>] | binfmt-match <snapshot> <file>"
            );
            std::process::exit(2);
        }
    }
}
