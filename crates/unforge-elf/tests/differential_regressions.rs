//! Regressions found by differential fuzzing (fuzz/fuzz_targets/differential.rs)
//! against `object` and `goblin`. Each test embeds the input that exposed
//! the problem; fuzz/KNOWN_DIVERGENCES.md ("Findings in unforge-elf") has
//! the triage. Both findings are fixed; these tests keep them fixed.

use std::collections::BTreeMap;

use unforge_elf::{DiagnosticKind, ElfFile, InferenceSubject};

// gABI ch4 values, spelled out rather than taken from the code under test.
const SHT_SYMTAB: u32 = 2;

/// Diagnostic kind names with their number of occurrences.
fn kinds(data: &[u8]) -> BTreeMap<&'static str, usize> {
    let elf = ElfFile::parse(data).expect("ELF header");
    let mut m = BTreeMap::new();
    for d in elf.audit().diagnostics {
        *m.entry(d.kind.name()).or_insert(0) += 1;
    }
    m
}

