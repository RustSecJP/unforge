/// [`R2`] with section `index`'s `sh_entsize` replaced (ELF32 MSB).
fn r2_with_entsize(index: usize, entsize: u32) -> Vec<u8> {
    let elf = ElfFile::parse(R2).unwrap();
    let h = elf.header();
    let at = h.shoff as usize + index * usize::from(h.shentsize) + 36;
    let mut v = R2.to_vec();
    v[at..at + 4].copy_from_slice(&entsize.to_be_bytes());
    v
}

#[test]
fn r2_input_is_as_described() {
    let elf = ElfFile::parse(R2).unwrap();
    let (s4, s5) = (
        elf.section_header(4).unwrap(),
        elf.section_header(5).unwrap(),
    );
    assert_eq!((s4.sh_type, s5.sh_type), (SHT_SYMTAB, SHT_SYMTAB));
    assert_eq!((s4.offset, s4.size), (s5.offset, s5.size));
    assert_eq!((s4.entsize, s5.entsize), (16, 0xff));
    assert_eq!(elf.symbol_table(4).unwrap().len(), 4);
    assert_eq!(elf.symbol_table(5).unwrap().len(), 0);
    let audit = elf.audit();
    assert!(audit.diagnostics.iter().any(|d| matches!(
        d.kind,
        DiagnosticKind::DuplicateTable {
            index: 5,
            same_as: 4
        }
    )));
}

#[test]
fn r2_duplicate_table_with_larger_entsize_is_reported() {
    let elf = ElfFile::parse(R2).unwrap();
    let audit = elf.audit();
    assert!(
        audit.diagnostics.iter().any(|d| matches!(
            d.kind,
            DiagnosticKind::SymbolEntrySize {
                table: 5,
                found: 0xff
            }
        )),
        "symbol table [5] is read with stride 0xff (0 symbols, [4] has 4 over the same bytes) \
         but no SymbolEntrySize is reported for it"
    );
}

#[test]
fn r2_duplicate_table_with_inferred_entsize_records_the_inference() {
    let data = r2_with_entsize(5, 0);
    let elf = ElfFile::parse(&data).unwrap();
    let t = elf.symbol_table(5).unwrap();
    assert!(
        t.entry_size_inferred(),
        "sh_entsize 0 is replaced by sizeof(Elf32_Sym)"
    );
    let audit = elf.audit();
    assert!(audit.inferred, "the file needs an inference");
    assert!(
        audit.diagnostics.iter().any(|d| match &d.kind {
            DiagnosticKind::Inferred(i) =>
                matches!(i.subject, InferenceSubject::SymbolEntrySize { table: 5 }),
            _ => false,
        }),
        "symbol table [5] is read with an inferred stride, but no inference is recorded"
    );
}
