/// File offsets of the last byte of `.shstrtab` and of `.strtab` in [`R1`].
const R1_SHSTRTAB_LAST: usize = 0x40 + 26 - 1;
const R1_STRTAB_LAST: usize = 0x5a + 8 - 1;

fn r1_with_nul_at(offsets: &[usize]) -> Vec<u8> {
    let mut v = R1.to_vec();
    for &o in offsets {
        v[o] = 0;
    }
    v
}

#[test]
fn r1_input_is_as_described() {
    let elf = ElfFile::parse(R1).unwrap();
    let names = elf.section_name_table().unwrap();
    assert_eq!(names.last(), Some(&b'b'));
    let strtab_sh = elf.section_header(3).unwrap();
    assert_eq!(
        elf.section_name(&strtab_sh).ok(),
        None,
        "name of [3] runs off the table"
    );
    let symtab = elf.symbol_table(2).unwrap();
    assert_eq!(symtab.strtab().and_then(|s| s.last()), Some(&b'r'));
    let syms: Vec<_> = symtab.iter().collect();
    assert_eq!(symtab.name(&syms[1]).unwrap(), b"foo");
    assert!(symtab.name(&syms[2]).is_err(), "\"bar\" has no NUL");
    // With the NULs in place every name reads and nothing is reported.
    let fixed = r1_with_nul_at(&[R1_SHSTRTAB_LAST, R1_STRTAB_LAST]);
    let elf = ElfFile::parse(&fixed).unwrap();
    assert_eq!(
        elf.section_name(&elf.section_header(3).unwrap()).unwrap(),
        b".strta"
    );
}

#[test]
fn r1_unterminated_section_name_table_is_reported() {
    let unterminated = r1_with_nul_at(&[R1_STRTAB_LAST]);
    let terminated = r1_with_nul_at(&[R1_SHSTRTAB_LAST, R1_STRTAB_LAST]);
    let (bad, good) = (kinds(&unterminated), kinds(&terminated));
    assert_ne!(
        bad, good,
        "section [3]'s name cannot be read (no NUL before the end of .shstrtab), \
         but the audit is identical to the terminated file's: {bad:?}"
    );
}

#[test]
fn r1_unterminated_symbol_string_table_is_reported() {
    let unterminated = r1_with_nul_at(&[R1_SHSTRTAB_LAST]);
    let terminated = r1_with_nul_at(&[R1_SHSTRTAB_LAST, R1_STRTAB_LAST]);
    let (bad, good) = (kinds(&unterminated), kinds(&terminated));
    assert_ne!(
        bad, good,
        "symbol [2]'s name cannot be read (no NUL before the end of .strtab), \
         but the audit is identical to the terminated file's: {bad:?}"
    );
}

